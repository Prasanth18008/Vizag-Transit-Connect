// Helper to make a BusStop from standard dictionary key
function createStop(
  routePrefix: string,
  key: string,
  distKm: number,
  isStage: boolean = true,
  overrideName?: { en: string; te: string; hi: string }
): BusStop {
  const coord = STOP_COORDS[key] || {
    lat: 17.7289,
    lng: 83.3032,
    en: key,
    te: key,
    hi: key,
  };
  return {
    id: `stop-${routePrefix}-${key}`,
    name: overrideName || { en: coord.en, te: coord.te, hi: coord.hi },
    lat: coord.lat,
    lng: coord.lng,
    distanceFromStartKm: distKm,
    isStageStop: isStage,
    landmark: coord.landmark ? { en: coord.landmark, te: coord.landmark, hi: coord.landmark } : undefined,
  };
}

// Helper to generate cumulative stops
function buildRouteStops(routePrefix: string, stopKeys: string[], totalDistanceKm: number): BusStop[] {
  const count = stopKeys.length;
  return stopKeys.map((key, idx) => {
    const fraction = count <= 1 ? 0 : idx / (count - 1);
    const dist = Number((fraction * totalDistanceKm).toFixed(1));
    return createStop(routePrefix, key, dist, idx === 0 || idx === count - 1 || idx % 2 === 0);
  });
}

